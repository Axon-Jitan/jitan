import 'db_row.dart';

/// Runs SQL. Implemented by the connection pool ([Database]) and by the
/// single connection inside a transaction, so repository methods work the
/// same in and out of a transaction.
///
/// Statements use named parameters (`:name`). Only `String`, `int`, `bool`
/// and `null` values are accepted, so nothing is stringified implicitly.
abstract interface class SqlExecutor {
  /// A statement that returns rows (SELECT).
  Future<List<DbRow>> query(String sql, [Map<String, Object?> params = const {}]);

  /// A statement that changes data (INSERT/UPDATE/DELETE).
  Future<SqlWriteResult> execute(String sql, [Map<String, Object?> params = const {}]);
}

/// Runs several statements atomically.
abstract interface class TransactionRunner {
  /// Runs [action] in one transaction: commits when it completes, rolls back
  /// and rethrows when it throws.
  Future<T> transaction<T>(Future<T> Function(SqlExecutor tx) action);
}

/// Outcome of a write statement.
class SqlWriteResult {
  const SqlWriteResult({required this.affectedRows, required this.lastInsertId});

  final int affectedRows;

  /// The AUTO_INCREMENT id generated by an INSERT (0 when none).
  final int lastInsertId;
}
